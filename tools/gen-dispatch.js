#!/usr/bin/env node
// Generate ported/auto/_dispatch.js: a single module that imports every
// FUN_<addr> from ported/auto/*.js and exports a Map<addr, fn> for the
// runtime's state.fnDispatch table. This is what lets DispatchMessageA
// call back into ported WindowProcs by address.
//
// Generated on demand; fast (no parsing, just file listing + name building).

import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const PORTED = resolve(HERE, "../ported/auto");
const OUT = resolve(PORTED, "_dispatch.js");

const files = readdirSync(PORTED)
  .filter(f => /^[0-9a-f]+\.js$/.test(f))
  .sort();

const lines = [
  "// AUTO-GENERATED by tools/gen-dispatch.js — do not edit by hand.",
  "//",
  "// Maps every ported function's RVA (number) to its JS implementation.",
  "// runtime/harness.js loads this into state.fnDispatch so DispatchMessageA",
  "// and SendMessageA can call back into ported WindowProcs.",
  "",
];

// Imports
for (const f of files) {
  const addr = f.replace(/\.js$/, "");
  lines.push(`import { FUN_${addr.padStart(8, "0")} } from "./${f}";`);
}
lines.push("");

// Map
lines.push("export const dispatch = new Map([");
for (const f of files) {
  const addr = f.replace(/\.js$/, "");
  lines.push(`  [0x${addr}, FUN_${addr.padStart(8, "0")}],`);
}
lines.push("]);");
lines.push("");
lines.push(`export const dispatchSize = ${files.length};`);
lines.push("");

writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} with ${files.length} entries`);

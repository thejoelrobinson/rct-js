#!/usr/bin/env node
// Generate runtime/win32.js + runtime/win32/stubs.js from the actual set of
// names imported by ported/auto/*.js. Re-runs whenever the surface or any
// sub-module's exports change.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const PORTED = resolve(ROOT, "ported/auto");
const WIN32_DIR = resolve(ROOT, "runtime/win32");

// 1. Discover the actual import surface from ported/auto/*.js.
const surface = new Set();
for (const f of readdirSync(PORTED)) {
  if (!f.endsWith(".js")) continue;
  const src = readFileSync(resolve(PORTED, f), "utf8");
  const m = src.match(/import\s*\{\s*([^}]+)\s*\}\s*from\s*"(?:\.\.\/)+runtime\/win32\.js"/);
  if (!m) continue;
  for (const name of m[1].split(",")) {
    const trimmed = name.trim();
    if (trimmed) surface.add(trimmed);
  }
}

// 2. For each sub-module under runtime/win32/, collect its exports.
const subModules = readdirSync(WIN32_DIR)
  .filter(f => f.endsWith(".js") && f !== "stubs.js");
const exportsByModule = new Map();
const allImpl = new Set();
for (const f of subModules) {
  const src = readFileSync(resolve(WIN32_DIR, f), "utf8");
  const exports = new Set();
  const re = /export\s+function\s+([A-Z][A-Za-z0-9_]*)\b/g;
  for (const m of src.matchAll(re)) {
    exports.add(m[1]);
    allImpl.add(m[1]);
  }
  exportsByModule.set(f.replace(/\.js$/, ""), exports);
}

// 3. Names in the surface not provided by any sub-module → stub them.
const stubs = [...surface].filter(n => !allImpl.has(n)).sort();

// 4. Emit runtime/win32/stubs.js
const stubsHeader = `// AUTO-GENERATED by tools/gen-win32-barrel.js — do not edit by hand.
//
// Stub Win32 functions that are imported by ported/auto/*.js but not yet
// implemented. Each returns 0 and warns once. As real implementations land
// in runtime/win32/<dll>.js, the corresponding name disappears from this
// file on the next regeneration.

const _warned = new Set();
function stub(name) {
  return (heap, ...args) => {
    if (!_warned.has(name)) {
      _warned.add(name);
      if (typeof console !== "undefined") {
        console.warn("[runtime/win32 stub]", name);
      }
    }
    return 0;
  };
}

`;
const stubsBody = stubs.map(n => `export const ${n} = stub("${n}");`).join("\n");
writeFileSync(resolve(WIN32_DIR, "stubs.js"), stubsHeader + stubsBody + "\n");

// 5. Emit runtime/win32.js — barrel that re-exports from each sub-module
//    plus stubs.js. We use `export { Name } from "./win32/<mod>.js"` lines
//    so static analysis works for ported code's `import { Name }` sites.
let barrel = `// AUTO-GENERATED by tools/gen-win32-barrel.js — do not edit by hand.
//
// Win32 surface barrel. Each name imported by ported/auto/*.js is re-exported
// here from either a real per-DLL sub-module or runtime/win32/stubs.js.
// Run \`node tools/gen-win32-barrel.js\` to regenerate after editing
// sub-modules or after re-running the C-to-JS translator.

`;
for (const [mod, exps] of exportsByModule) {
  const wanted = [...exps].filter(n => surface.has(n)).sort();
  if (wanted.length === 0) continue;
  barrel += `export { ${wanted.join(", ")} } from "./win32/${mod}.js";\n`;
}
if (stubs.length > 0) {
  barrel += `export { ${stubs.join(", ")} } from "./win32/stubs.js";\n`;
}
writeFileSync(resolve(ROOT, "runtime/win32.js"), barrel);

// 6. Report
const implInSurface = [...surface].filter(n => allImpl.has(n));
console.log(`Win32 surface:    ${surface.size}`);
console.log(`Real implementations: ${implInSurface.length} (${(implInSurface.length / surface.size * 100).toFixed(1)}%)`);
console.log(`Stubs:                ${stubs.length}`);
for (const [mod, exps] of exportsByModule) {
  const inSurface = [...exps].filter(n => surface.has(n)).length;
  console.log(`  win32/${mod}.js: ${inSurface} surface fns implemented`);
}

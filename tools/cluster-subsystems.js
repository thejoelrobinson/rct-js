#!/usr/bin/env node
// Cluster the call graph into named subsystems ("chunks").
//
// Reads tools/callgraph.json + tools/subsystems.config.json. BFS from each
// subsystem's roots (following static callees + indirect dispatcher edges),
// then assigns every reached function to the MOST-SPECIFIC subsystem that
// reaches it (highest `priority`). Functions reached by >=3 subsystems with
// no single highest-priority winner fall into `shared-util`. Functions
// reached by nothing are `unreached` (dead from these roots, or reachable
// only via an indirect edge we haven't mapped yet).
//
// Output: tools/subsystems.json (canonical chunk list, consumed by
// capture-lockstep.js / diff-lockstep.js via --subsystem=<name>) and a
// human-readable tools/subsystems.md.
//
// Usage: node tools/cluster-subsystems.js

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");

// Prefer the dynamic graph (static ∪ traced indirect edges) when present; it
// resolves the 277 callIndirect sites the static-only graph misses. Fall back
// to the static graph. Pass --static to force the static-only graph.
const forceStatic = process.argv.includes("--static");
const DYN = resolve(ROOT, "tools/dynamic-callgraph.json");
const STAT = resolve(ROOT, "tools/callgraph.json");
let cgPath = STAT;
if (!forceStatic) { try { readFileSync(DYN); cgPath = DYN; } catch {} }
const cg = JSON.parse(readFileSync(cgPath, "utf8"));
const usingDynamic = cgPath === DYN;
console.error(`[cluster] graph: ${usingDynamic ? "dynamic (static ∪ traced indirect)" : "static-only"}`);
const cfg = JSON.parse(readFileSync(resolve(ROOT, "tools/subsystems.config.json"), "utf8"));

const allCallees = (addr) => {
  const node = cg.nodes[addr];
  // dynamic graph carries `allCallees` (static ∪ dynamic); static carries `callees`.
  const direct = node ? (node.allCallees || node.callees) : [];
  const indirect = cg.indirectEdges[addr] || [];
  return [...direct, ...indirect];
};

// BFS reachability from a set of roots.
function reach(roots) {
  const seen = new Set();
  const queue = [...roots];
  while (queue.length) {
    const a = queue.shift();
    if (seen.has(a)) continue;
    seen.add(a);
    for (const c of allCallees(a)) if (!seen.has(c)) queue.push(c);
  }
  return seen;
}

// reachedBy[fn] = [{name, priority}, ...]
const reachedBy = new Map();
const subsystemReach = {};
for (const s of cfg.subsystems) {
  const r = reach(s.roots);
  subsystemReach[s.name] = r;
  for (const fn of r) {
    if (!reachedBy.has(fn)) reachedBy.set(fn, []);
    reachedBy.get(fn).push({ name: s.name, priority: s.priority });
  }
}

// Assign each known function to its owner.
const owners = {}; // fn -> subsystem name
for (const fn of Object.keys(cg.nodes)) {
  const owners_ = reachedBy.get(fn);
  if (!owners_ || owners_.length === 0) { owners[fn] = "unreached"; continue; }
  const maxP = Math.max(...owners_.map((o) => o.priority));
  const top = owners_.filter((o) => o.priority === maxP);
  if (owners_.length >= 3 && top.length > 1) { owners[fn] = "shared-util"; continue; }
  owners[fn] = top[0].name;
}

// Build per-subsystem records.
const fanIn = {};
for (const a of Object.keys(cg.nodes)) for (const c of allCallees(a)) fanIn[c] = (fanIn[c] || 0) + 1;

const subsystems = {};
const bucketNames = [...cfg.subsystems.map((s) => s.name), "shared-util", "unreached"];
for (const name of bucketNames) subsystems[name] = { functions: [], manualCount: 0, codesegCount: 0 };

for (const [fn, owner] of Object.entries(owners)) {
  const node = cg.nodes[fn];
  const rec = subsystems[owner];
  rec.functions.push(fn);
  if (node.manual) rec.manualCount++;
  if (node.section === "CODESEG") rec.codesegCount++;
}

for (const name of bucketNames) {
  subsystems[name].functions.sort();
  subsystems[name].count = subsystems[name].functions.length;
}

const out = {
  meta: {
    totalFunctions: Object.keys(cg.nodes).length,
    generated: "run `node tools/cluster-subsystems.js` to refresh",
  },
  config: cfg.subsystems.map((s) => ({ name: s.name, priority: s.priority, roots: s.roots })),
  subsystems,
};
writeFileSync(resolve(ROOT, "tools/subsystems.json"), JSON.stringify(out, null, 2) + "\n");

// --- markdown summary ---
let md = `# Subsystem map\n\nGenerated by \`tools/cluster-subsystems.js\` from \`tools/callgraph.json\`.\nEach function is owned by the most-specific subsystem that reaches it from its roots.\n\n`;
md += `Total functions: ${out.meta.totalFunctions}\n\n`;
md += `| Subsystem | Funcs | @manual | CODESEG | Roots |\n|---|---:|---:|---:|---|\n`;
for (const s of cfg.subsystems) {
  const rec = subsystems[s.name];
  md += `| ${s.name} | ${rec.count} | ${rec.manualCount} | ${rec.codesegCount} | ${s.roots.join(", ") || "_(none yet)_"} |\n`;
}
md += `| shared-util | ${subsystems["shared-util"].count} | ${subsystems["shared-util"].manualCount} | ${subsystems["shared-util"].codesegCount} | _(>=3 subsystems, tie)_ |\n`;
md += `| unreached | ${subsystems["unreached"].count} | ${subsystems["unreached"].manualCount} | ${subsystems["unreached"].codesegCount} | _(not reached from any root)_ |\n`;
md += `\n## Notes\n\n- \`unreached\` is large until indirect jumptable edges are mapped in \`subsystems.config.json\` and roots for ride-sim/ui are filled in.\n- A subsystem is the unit of the per-chunk workflow: \`node tools/diff-lockstep.js --subsystem=<name>\`.\n`;
writeFileSync(resolve(ROOT, "tools/subsystems.md"), md);

console.log(`wrote tools/subsystems.json + tools/subsystems.md`);
for (const s of cfg.subsystems) {
  console.log(`  ${s.name.padEnd(14)} ${String(subsystems[s.name].count).padStart(4)} funcs  (${subsystems[s.name].manualCount} @manual, ${subsystems[s.name].codesegCount} CODESEG)`);
}
console.log(`  ${"shared-util".padEnd(14)} ${String(subsystems["shared-util"].count).padStart(4)} funcs`);
console.log(`  ${"unreached".padEnd(14)} ${String(subsystems["unreached"].count).padStart(4)} funcs`);
